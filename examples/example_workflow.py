"""End-to-end demonstration on SYNTHETIC data.

Steps: load -> inspect -> validate -> explicit cleaning -> score -> reliability ->
descriptives -> correlations -> report.

Nothing here is an empirical finding: the data come from a pseudo-random
generator (see ``generate_synthetic_data.py``). The cleaning decisions below are
made *by the analyst in this script*; the toolkit never cleans data silently.

Usage:
    python examples/example_workflow.py [--data PATH] [--output DIR]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

import behavioral_data_toolkit as bdt

HERE = Path(__file__).resolve().parent
ITEMS = [f"sw{i}" for i in range(1, 7)] + [f"sf{i}" for i in range(1, 5)]
WELLBEING = bdt.ScaleDefinition(
    name="synthetic_wellbeing",
    items=tuple(f"sw{i}" for i in range(1, 7)),
    min_value=1,
    max_value=5,
    reverse_items=("sw2", "sw5"),
    min_valid=5,  # illustrative partial-mean rule; real instruments define their own
)
FOCUS = bdt.ScaleDefinition(
    name="synthetic_focus",
    items=tuple(f"sf{i}" for i in range(1, 5)),
    min_value=1,
    max_value=5,
)
RULES = {item: bdt.ValueRule(minimum=1, maximum=5) for item in ITEMS}


def run(data_path: Path, output_dir: Path) -> bdt.AnalysisReport:
    """Run the demonstration analysis and write the report files to ``output_dir``."""
    # 1. Load and inspect
    df = bdt.load_csv(data_path, required_columns=["participant_id", *ITEMS])
    structure = bdt.inspect_dataframe(df)

    # 2. Validate (findings only; nothing is changed yet)
    before = bdt.data_quality_summary(df, duplicate_subset=["participant_id"], rules=RULES)

    # 3. Explicit analyst decisions: keep first record per participant; treat
    #    out-of-range codes as missing.
    clean = df.drop_duplicates(subset="participant_id", keep="first").copy()
    clean[ITEMS] = clean[ITEMS].astype(float)
    for row in before.invalid.itertuples():
        clean.loc[row.row, row.column] = np.nan
    clean = clean.reset_index(drop=True)
    after = bdt.data_quality_summary(clean, duplicate_subset=["participant_id"], rules=RULES)

    # 4. Score
    scores = bdt.score_questionnaires(clean, [WELLBEING, FOCUS])

    # 5. Internal consistency (reverse-score first; see docs/STATISTICAL_METHODS.md)
    reversed_items = bdt.reverse_score(clean, 1, 5, columns=list(WELLBEING.reverse_items))
    alpha_wellbeing = bdt.cronbach_alpha(reversed_items, list(WELLBEING.items))
    alpha_focus = bdt.cronbach_alpha(clean, list(FOCUS.items))

    # 6. Descriptives and correlations
    summary = bdt.distribution_summary(scores["synthetic_wellbeing"])
    analysis = pd.concat([scores, clean[["age", "screen_hours"]]], axis=1)
    matrix = bdt.correlation_matrix(analysis, method="pearson", missing="pairwise")
    rank_corr = bdt.spearman(scores["synthetic_wellbeing"], scores["synthetic_focus"])

    # 7. Report
    report = bdt.AnalysisReport(
        "Synthetic demonstration analysis",
        data=clean,
        parameters={
            "data_source": "synthetic (seeded pseudo-random generator)",
            "duplicate_rule": "keep first record per participant_id",
            "invalid_value_rule": "out-of-range codes set to missing",
            "wellbeing_scoring": WELLBEING.to_dict(),
            "focus_scoring": FOCUS.to_dict(),
            "alpha_missing": "listwise",
            "correlation_missing": "pairwise",
        },
        include_timestamp=False,  # keeps the committed example output reproducible
    )
    report.add_text(
        "About this report",
        "All data are synthetic and were generated by a pseudo-random number generator. "
        "The scales are invented for demonstration. Nothing here is an empirical finding "
        "about real people.",
    )
    report.add_result("Data structure", structure)
    report.add_result("Data quality before cleaning", before)
    report.add_result("Data quality after cleaning", after)
    report.add_result("Cronbach's alpha: synthetic_wellbeing", alpha_wellbeing)
    report.add_result("Cronbach's alpha: synthetic_focus", alpha_focus)
    report.add_text(
        "Reading alpha",
        "Alpha summarises inter-item covariance in this sample. It is not evidence of "
        "unidimensionality or construct validity.",
    )
    report.add_result("Distribution: synthetic_wellbeing", summary)
    report.add_result("Pearson correlation matrix (pairwise deletion)", matrix)
    report.add_result("Spearman: wellbeing vs focus", rank_corr)

    output_dir.mkdir(parents=True, exist_ok=True)
    report.to_json(output_dir / "example_report.json")
    report.to_markdown(output_dir / "example_report.md")
    try:
        bdt.plot_distribution(
            scores["synthetic_wellbeing"], title="synthetic_wellbeing"
        ).figure.savefig(output_dir / "distribution.png", dpi=120)
        bdt.plot_correlation_heatmap(matrix).figure.savefig(
            output_dir / "correlations.png", dpi=120
        )
    except ImportError:
        print("Matplotlib not installed; skipping figures.")
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--data", type=Path, default=HERE / "data" / "synthetic_survey.csv")
    parser.add_argument("--output", type=Path, default=HERE / "output")
    args = parser.parse_args()
    report = run(args.data, args.output)
    print(
        f"Report written to {args.output} (data fingerprint: "
        f"{report.metadata['data_fingerprint_sha256'][:12]}...)"
    )


if __name__ == "__main__":
    main()
